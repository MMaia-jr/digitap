import { afterAll, afterEach, beforeAll, beforeEach, expect, it } from 'vitest';
import { randomUUID } from 'node:crypto';
import { Client } from 'pg';

const additions = ['sujeitos_publicadores', 'pessoas_fisicas', 'coletivos_informais', 'vinculos_publicadores', 'atestacoes_representacao', 'casos_moderacao'];
const legacy = ['organizacoes', 'contas_acesso', 'atividades', 'registros_realizacao', 'evidencias', 'autorizacoes_publicacao', 'apoios', 'parceiros', 'eventos_editoriais'];
let db: Client | undefined;
let seeded = false;
let org: string, account: string, user: string;
let subjects: string[] = [];

beforeAll(async () => {
  if (process.env.A_PRACA_ALLOW_FIXTURE_CLEANUP !== '1') throw new Error('Fixtures locais exigem autorização explícita.');
  const connectionString = 'postgresql://postgres:postgres@127.0.0.1:56152/postgres';
  const url = new URL(connectionString);
  if (url.hostname !== '127.0.0.1' || url.port !== '56152') throw new Error('Alvo fora do escopo local exclusivo.');
  db = new Client({ connectionString });
  await db.connect();
});

beforeEach(async () => {
  if (!db) throw new Error('Banco não conectado.');
  org = randomUUID(); account = randomUUID(); user = randomUUID(); subjects = [];
  await db.query('begin');
  await db.query('insert into auth.users(id) values ($1)', [user]);
  await db.query('insert into public.organizacoes(id,nome_publico) values ($1,$2)', [org, 'Organização Fictícia EXPAND']);
  await db.query('insert into public.contas_acesso(id,auth_user_id,organizacao_id) values ($1,$2,$3)', [account, user, org]);
  seeded = true;
});

afterEach(async () => {
  if (!db) return;
  await db.query('rollback');
  // P04 deliberately issues COMMIT. If integrity is broken and it succeeds,
  // delete only the exact random IDs generated by this test, never by prefix.
  if (seeded) {
    const exists = await db.query("select to_regclass('public.sujeitos_publicadores') as name");
    if (exists.rows[0].name) await db.query('delete from public.sujeitos_publicadores where id=any($1::uuid[])', [subjects]);
    await db.query('delete from public.contas_acesso where id=$1', [account]);
    await db.query('delete from public.organizacoes where id=$1', [org]);
    await db.query('delete from auth.users where id=$1', [user]);
    seeded = false;
  }
});
afterAll(async () => { await db?.end(); });

async function parent(type: string, organization: string | null = null) {
  const id = randomUUID(); subjects.push(id);
  await db!.query('insert into public.sujeitos_publicadores(id,tipo,nome_publico,origem,criado_por_conta_id,organizacao_legada_id) values ($1,$2,$3,$4,$5,$6)', [id, type, 'Sujeito Fictício EXPAND', 'cadastro', account, organization]);
  return id;
}

it('I4-P01 PG: sujeito tipado com filha PF completa é válido ao fim da transação', async () => {
  const id = await parent('pessoa_fisica');
  await db!.query('insert into public.pessoas_fisicas(sujeito_id,conta_id) values ($1,$2)', [id, account]);
  await db!.query('set constraints all immediate');
  expect((await db!.query('select tipo from public.sujeitos_publicadores where id=$1', [id])).rows).toEqual([{ tipo: 'pessoa_fisica' }]);
});
it('I4-P02 PG: FK tipada recusa filha PF em sujeito coletivo', async () => {
  const id = await parent('coletivo_informal');
  await expect(db!.query('insert into public.pessoas_fisicas(sujeito_id,conta_id) values ($1,$2)', [id, account])).rejects.toMatchObject({ code: '23503' });
});
it('I4-P03 PG: FK tipada recusa filha coletivo em sujeito PF', async () => {
  const id = await parent('pessoa_fisica');
  await expect(db!.query('insert into public.coletivos_informais(sujeito_id,nome_em_curadoria) values ($1,$2)', [id, 'Coletivo Fictício'])).rejects.toMatchObject({ code: '23503' });
});
it.each(['pessoa_fisica', 'coletivo_informal'])('I4-P04 PG: pai %s sem filha é recusado no COMMIT', async type => {
  await parent(type);
  await expect(db!.query('commit')).rejects.toMatchObject({ code: '23514' });
});
it('I4-P05 PG: UNIQUE recusa segunda PF para a mesma conta', async () => {
  const a = await parent('pessoa_fisica'), b = await parent('pessoa_fisica');
  await db!.query('insert into public.pessoas_fisicas(sujeito_id,conta_id) values ($1,$2)', [a, account]);
  await expect(db!.query('insert into public.pessoas_fisicas(sujeito_id,conta_id) values ($1,$2)', [b, account])).rejects.toMatchObject({ code: '23505' });
});
it('I4-P06 PG: atividade organizacional não aceita sujeito de outra organização', async () => {
  const other = randomUUID();
  await db!.query('insert into public.organizacoes(id,nome_publico) values ($1,$2)', [other, 'Outra Organização Fictícia']);
  const subject = await parent('organizacao', other);
  await expect(db!.query("insert into public.atividades(organizacao_id,criada_por_conta_id,sujeito_id,titulo,descricao,inicio_previsto,orientacao_acesso) values ($1,$2,$3,'Atividade fictícia','Descrição exclusivamente fictícia',now(),'Acesso fictício')", [org, account, subject])).rejects.toMatchObject({ code: '23514' });
});

for (const table of [...additions, ...legacy]) {
  it(`${additions.includes(table) ? 'I4-P36' : 'H02 legado'} PG: ${table} tem RLS, zero policies e nenhum privilégio cliente`, async () => {
    const result = await db!.query('select relrowsecurity from pg_class where oid=to_regclass($1)', [`public.${table}`]);
    expect(result.rows).toEqual([{ relrowsecurity: true }]);
    expect((await db!.query('select * from pg_policies where schemaname=$1 and tablename=$2', ['public', table])).rows).toHaveLength(0);
    for (const role of ['anon', 'authenticated']) for (const privilege of ['SELECT', 'INSERT', 'UPDATE', 'DELETE']) {
      expect((await db!.query('select has_table_privilege($1,$2,$3) allowed', [role, `public.${table}`, privilege])).rows[0].allowed).toBe(false);
    }
    for (const role of ['anon', 'authenticated']) for (const sql of [`select * from public.${table}`, `insert into public.${table} default values`, `update public.${table} set ${table === 'pessoas_fisicas' || table === 'coletivos_informais' ? 'sujeito_id=sujeito_id' : 'id=id'}`, `delete from public.${table}`]) {
      await db!.query('savepoint denied');
      await db!.query(`set local role ${role}`);
      await expect(db!.query(sql)).rejects.toMatchObject({ code: '42501' });
      await db!.query('rollback to savepoint denied');
      await db!.query('release savepoint denied');
    }
  });
}
